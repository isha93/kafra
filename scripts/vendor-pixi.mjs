/**
 * Copy the two PixiJS files the city needs into web/vendor/, so Kafra runs
 * with no node_modules and no install step.
 *
 * To upgrade PixiJS:
 *   npm install --no-save --ignore-scripts pixi.js@<version>
 *   node scripts/vendor-pixi.mjs
 *   rm -rf node_modules
 *
 * Writes:
 *   web/vendor/pixi.js       PixiJS as a classic script (sets globalThis.PIXI)
 *   web/vendor/pixi-csp.js   PixiJS's unsafe-eval package. Despite the name it
 *                            *removes* PixiJS's need for eval, so the page's CSP
 *                            can forbid eval entirely.
 *   web/vendor/pixi.mjs      an ES module re-exporting every name from the
 *                            global, so the city can `import { … } from` it
 *   web/vendor/LICENSE-pixi  PixiJS's MIT licence
 */
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = (rel) => fileURLToPath(new URL(`../${rel}`, import.meta.url));
const pkg = root('node_modules/pixi.js/');
const out = root('web/vendor/');
mkdirSync(out, { recursive: true });

const version = JSON.parse(readFileSync(`${pkg}package.json`, 'utf8')).version;
copyFileSync(`${pkg}dist/pixi.min.js`, `${out}pixi.js`);
copyFileSync(`${pkg}dist/packages/unsafe-eval.min.js`, `${out}pixi-csp.js`);
copyFileSync(`${pkg}LICENSE`, `${out}LICENSE-pixi`);

// Every name the ESM build exports, re-exported from the global the classic script sets.
const esm = readFileSync(`${pkg}dist/pixi.min.mjs`, 'utf8');
const block = esm.match(/export\s*\{([^}]*)\}\s*;?\s*(\/\/.*)?\s*$/)?.[1] ?? '';
const names = block.split(',').map((s) => s.trim().split(/\s+as\s+/).pop()).filter((n) => /^[A-Za-z_$][\w$]*$/.test(n));
if (names.length < 100) throw new Error(`only ${names.length} exports found; has the PixiJS build format changed?`);
writeFileSync(`${out}pixi.mjs`, `// PixiJS ${version} as an ES module. Generated by scripts/vendor-pixi.mjs; do not edit.
// The page loads pixi.js and pixi-csp.js as classic scripts first (see index.html).
const P = globalThis.PIXI;
if (!P) throw new Error('PixiJS did not load');
export const { ${names.join(', ')} } = P;
`);
console.log(`PixiJS ${version}: ${names.length} exports → web/vendor/`);
